# Renders the catalog as the docs page and the credentials examples a developer copies from.
# Output holds hints only; a value never appears in either.
class RequiredProductionConfigCatalog
  module Generator
    GENERATED = "Generated by bin/rails required_production_config:generate. Don't edit.".freeze
    CATALOG_HEADER = "Describes what production needs. Values go in credentials, deploy.yml or fnox; never here.".freeze
    DOCS_PATH = "app/docs/developer/required-production-config.md".freeze
    EXAMPLE_PATH = "config/credentials/production.yml.example".freeze
    LOCAL_EXAMPLE_PATH = "config/credentials/production.local.yml.example".freeze
    STEP_TITLES = { 4 => "Production secrets and mail", 6 => "Configure the deploy and go live" }.freeze
    HOME_LABELS = {
      "env" => "`env.clear` in config/deploy.yml", "credentials" => "Encrypted credentials",
      "kamal_secret" => "`.kamal/secrets`", "dns" => "Your DNS provider", "dashboard" => "A provider dashboard"
    }.freeze
    GENERATED_EXAMPLE = /\A<(written by|from bin\/rails)/
    COLUMNS = [ "Input", "Where it lives", "Needed", "Where to get it", "How to set it", "Can it be regenerated?" ].freeze

    module_function

    # Writes the docs page and example from the template entries, and a local example only
    # when the fork's own entries include credentials. Returns the paths written.
    def write(root:)
      root = Pathname(root)
      entries = RequiredProductionConfigCatalog.load(root: root).entries
      template, local = entries.partition { |entry| entry.source == :template }
      written = { DOCS_PATH => docs_page(template), EXAMPLE_PATH => credentials_example(credentials_of(template)) }
      local_credentials = credentials_of(local)
      written[LOCAL_EXAMPLE_PATH] = credentials_example(local_credentials) if local_credentials.any?
      written.each { |path, content| write_file(root.join(path), content) }
      root.join(LOCAL_EXAMPLE_PATH).delete if local_credentials.empty? && root.join(LOCAL_EXAMPLE_PATH).exist?
      written.keys
    end

    def docs_page(entries)
      sections = entries.group_by(&:step).sort.map { |step, group| step_section(step, group) }
      [ front_matter, intro, *sections, closing ].join("\n\n") + "\n"
    end

    def credentials_example(entries)
      groups = entries.group_by { |entry| entry.key.split(".").first }.values
      header = [ "# #{GENERATED}", "# #{CATALOG_HEADER}" ]
      ([ header.join("\n") ] + groups.map { |group| credentials_section(group) }).join("\n\n") + "\n"
    end

    def credentials_of(entries) = entries.select { |entry| entry.home == "credentials" }

    def write_file(path, content)
      FileUtils.mkdir_p(path.dirname)
      File.write(path, content)
    end

    def front_matter
      <<~YAML.chomp
        ---
        title: What production needs
        description: Every input production needs, grouped by quickstart step, with where it lives, where to get it and how to set it. Generated from the catalog.
        keywords: production config credentials env secrets deploy check kamal catalog required
        ---
      YAML
    end

    def intro
      <<~MD.chomp
        # What production needs

        This page is generated from `config/required_production_config.yml`, so it
        never drifts from the code. It holds no values, only where each one lives and
        where to get it. `bin/rails deploy:check` reads the same catalog and tells
        you which of these your deploy is still missing.
      MD
    end

    def closing
      "A fork adds its own inputs in `config/required_production_config.local.yml`. " \
        "Run `bin/rails deploy:check` there to see them alongside the ones above."
    end

    def step_section(step, entries)
      title = STEP_TITLES.fetch(step) { "Step #{step}" }
      rows = entries.map { |entry| table_row(entry) }
      [ "## Step #{step}: #{title}", table(rows) ].join("\n\n")
    end

    def table(rows)
      head = "| #{COLUMNS.join(" | ")} |"
      divider = "| #{COLUMNS.map { "---" }.join(" | ")} |"
      [ head, divider, *rows ].join("\n")
    end

    def table_row(entry)
      cells = [ "`#{entry.key}`: #{entry.purpose}", HOME_LABELS.fetch(entry.home), needed(entry),
               entry.where, entry.set_with, entry.regenerable || "Yes, any time" ]
      "| #{cells.map { |cell| cell.to_s.gsub("|", "\\|").gsub(%r{https?://[\w./-]+}) { |url| "`#{url}`" } }.join(" | ")} |"
    end

    def needed(entry)
      return entry.required.capitalize unless entry.required.is_a?(Hash)

      condition, target = entry.required.first
      case condition
      when "when_env_set" then "When `#{target}` is set"
      when "when_env_unset" then "When `#{target}` is not set"
      when "when_preset" then "On the #{target} preset"
      when "when_credential_set" then "When `#{target}` is set"
      end
    end

    def credentials_section(group)
      notes = group.map { |entry| "# #{entry.key}: #{requirement(entry)}. Get it: #{entry.where}. Set it: #{entry.set_with}" }
      return (notes + [ instruction(group.first) ]).join("\n") if group.all? { |entry| generated?(entry) }

      (notes + yaml_lines(group)).join("\n")
    end

    def requirement(entry)
      return (entry.required == "always" ? "required" : "optional") if entry.required.is_a?(String)

      condition, target = entry.required.first
      case condition
      when "when_env_set" then "required when #{target} is set"
      when "when_env_unset" then "required when #{target} is not set"
      when "when_preset" then "required on the #{target} preset"
      when "when_credential_set" then "required when #{target} is set"
      end
    end

    def generated?(entry) = GENERATED_EXAMPLE.match?(entry.example)

    def instruction(entry)
      if entry.key == "secret_key_base"
        "# secret_key_base: written by bin/rails credentials:edit when it creates the file; leave it as it is"
      else
        "# #{entry.key.split(".").first}: run bin/encryption-setup, which adds this block"
      end
    end

    def yaml_lines(group)
      tree = group.each_with_object({}) do |entry, root|
        *path, leaf = entry.key.split(".")
        path.reduce(root) { |node, name| node[name] ||= {} }[leaf] = entry.example
      end
      render_tree(tree, 0).map { |line| "# #{line}" }
    end

    def render_tree(node, depth)
      node.flat_map do |name, child|
        pad = "  " * depth
        child.is_a?(Hash) ? [ "#{pad}#{name}:" ] + render_tree(child, depth + 1) : [ "#{pad}#{name}: #{child}" ]
      end
    end
  end
end
