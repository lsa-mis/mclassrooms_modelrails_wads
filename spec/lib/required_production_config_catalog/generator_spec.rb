require "rails_helper"
require "tmpdir"
require "fileutils"

RSpec.describe RequiredProductionConfigCatalog::Generator do
  let(:catalog) { RequiredProductionConfigCatalog.load(root: Rails.root) }
  let(:entries) { catalog.entries }
  let(:example) { described_class.credentials_example(entries.select { |entry| entry.home == "credentials" }) }
  let(:local_entry) do
    {
      "home" => "credentials", "required" => "optional", "secret" => true,
      "purpose" => "Charges cards", "where" => "Stripe dashboard", "set_with" => "credentials:edit",
      "step" => 4, "example" => "<from Stripe → Developers → API keys>"
    }
  end

  def write_fork(local:)
    Dir.mktmpdir do |dir|
      FileUtils.mkdir_p(File.join(dir, "config"))
      FileUtils.cp(Rails.root.join("config/required_production_config.yml"), File.join(dir, "config"))
      File.write(File.join(dir, "config/required_production_config.local.yml"), { "inputs" => local }.to_yaml)
      described_class.write(root: Pathname(dir))
      yield Pathname(dir)
    end
  end

  it "starts the example with the generated line and the catalog header" do
    first, second = example.lines.first(2).map(&:chomp)

    expect(first).to eq("# Generated by bin/rails required_production_config:generate. Don't edit.")
    expect(second).to eq("# Describes what production needs. Values go in credentials, deploy.yml or fnox; never here.")
  end

  it "comments out every line of the example" do
    uncommented = example.lines.map(&:chomp).reject { |line| line.strip.empty? || line.start_with?("#") }

    expect(uncommented).to eq([])
  end

  it "puts no value in the example, only hints" do
    leaves = example.lines.map(&:chomp).grep(/\A#\s{3,}\S+: (\S.*)\z/) { Regexp.last_match(1) }

    expect(leaves).not_to be_empty
    expect(leaves).to all(satisfy { |leaf| RequiredProductionConfig.placeholder?(leaf) })
  end

  it "nests dotted keys as YAML" do
    expect(example).to include("# smtp:\n#   user_name: <from Postmark")
  end

  it "gives generated inputs an instruction, never a value" do
    expect(example).to include("# active_record_encryption: run bin/encryption-setup, which adds this block")
    expect(example).not_to match(/^#\s+primary_key:/)
  end

  it "lists every template entry on the docs page" do
    page = described_class.docs_page(entries)

    entries.each { |entry| expect(page).to include("`#{entry.key}`") }
    expect(page).to start_with("---\ntitle: What production needs\n")
    expect(page).to include("| Input | Where it lives | Needed | Where to get it | How to set it | Can it be regenerated? |")
    expect(page).to include("bin/rails deploy:check")
  end

  it "writes the local example only for local credential entries" do
    write_fork(local: { "stripe.secret_key" => local_entry }) do |root|
      local_example = root.join("config/credentials/production.local.yml.example").read

      expect(local_example).to include("# stripe:\n#   secret_key: <from Stripe")
      expect(local_example).not_to include("smtp")
      expect(root.join("config/credentials/production.yml.example").read).not_to include("stripe")
    end

    write_fork(local: { "STRIPE_MODE" => local_entry.merge("home" => "env", "example" => nil) }) do |root|
      expect(root.join("config/credentials/production.local.yml.example")).not_to exist
    end
  end
end
